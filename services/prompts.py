"""
Промпты для OpenAI API. Единственное место где редактируются тексты запросов.
"""

from constants import (
    GENRE_LABELS,
    GENRE_WRITING_GUIDE,
    MOOD_LABELS,
    MOOD_WRITING_GUIDE,
    VOICE_LABELS,
    VOICE_WRITING_GUIDE,
    LANG_PROMPT_LABELS,
)


def build_generate_prompt(
    genre: str,
    mood: str,
    voice: str,
    details: str,
    lang: str,
) -> tuple[str, str]:
    """
    Возвращает (system_prompt, user_prompt) для генерации текста песни.

    Промпт оптимизирован под движок Suno AI:
      • Короткие строки (6-12 слогов) — иначе Suno режет вокал.
      • Никаких мета-тегов и эмодзи в тексте — Suno зачитывает их буквально.
      • Жёсткая структура с бриджем — даёт эмоциональный пик.
      • Припев одинаков во всех повторах — это hook, который запоминается.
    """
    genre_label = GENRE_LABELS.get(genre, genre)
    mood_label  = MOOD_LABELS.get(mood, mood)
    voice_label = VOICE_LABELS.get(voice, voice)
    lang_label  = LANG_PROMPT_LABELS.get(lang, "русском")

    genre_guide = GENRE_WRITING_GUIDE.get(genre, "")
    mood_guide  = MOOD_WRITING_GUIDE.get(mood, "")
    voice_guide = VOICE_WRITING_GUIDE.get(voice, "")

    system_prompt = (
        "Ты — профессиональный автор песенных текстов с многолетним опытом. "
        "Пишешь живые, эмоциональные, рифмованные тексты, которые приятно петь и легко запомнить. "
        "Твои тексты идут в музыкальный движок Suno AI — поэтому ты строго соблюдаешь: "
        "короткие строки, чистые рифмы, отсутствие мета-тегов и эмодзи внутри текста. "
        "Ты пишешь на языке, указанном в запросе. "
        "Ты НИКОГДА не пишешь тексты с оскорблениями, угрозами, политическими лозунгами, "
        "сексуальным контентом, дискриминацией или призывами к насилию — даже если просят. "
        "В таких случаях вежливо отказываешь одной фразой и не пишешь песню."
    )

    user_prompt = f"""ЗАДАЧА: Написать персональную песню на {lang_label} языке.

ПАРАМЕТРЫ:
• Жанр: {genre_label}
• Настроение: {mood_label}
• Вокал: {voice_label}
• О ком/о чём песня: {details}

КАК ПИСАТЬ В ЭТОМ ЖАНРЕ:
{genre_guide}

КАК ОТРАЗИТЬ НАСТРОЕНИЕ:
{mood_guide}

ВОКАЛЬНАЯ ПОДАЧА:
{voice_guide}

СТРУКТУРА (обязательная):
[Куплет 1] — 4 строки, завязка истории
[Припев]   — 4 строки, главный хук с именем
[Куплет 2] — 4 строки, развитие истории
[Припев]   — те же 4 строки повторить ТОЧНО как первый раз
[Бридж]    — 2 строки, эмоциональный пик / поворот
[Припев]   — те же 4 строки, финал

ЖЁСТКИЕ ТРЕБОВАНИЯ:
1. Длина строк: 6-12 слогов. Не пиши длинных литературных строк — Suno их обрежет.
2. Рифма обязательна. Схема AABB или ABAB. Чистые рифмы, не «глагол-глагол».
3. ПРИПЕВ ОДИНАКОВЫЙ во всех трёх повторах — буква в букву. Это hook.
4. Имя из деталей упомяни минимум 2 раза, ОДНО упоминание обязательно в припеве.
5. Используй 3-5 конкретных деталей из описания (профессия, любимое, привычки, факты).
6. Эмоциональный пик — в бридже или финальном припеве.
7. Всего 200-280 слов.
8. Числа писать ТОЛЬКО словами: «тридцать пять», а не «35». Suno иначе ломается.

СТРОГО ЗАПРЕЩЕНО:
• Мета-теги в тексте: [гитара], [бит], (пауза), *шёпот*, *крик* — Suno зачитает буквально.
• Эмодзи внутри текста песни.
• Описания вступлений: «и тут вступает соло», «звучит фортепиано».
• Любые предисловия и пояснения: «Вот песня:», «Готово!», «Надеюсь понравится».
• Цифры цифрами.
• Английские слова, если язык не английский (кроме имён).

ФОРМАТ ОТВЕТА (строго так, без отклонений):
[Куплет 1]
строка
строка
строка
строка

[Припев]
строка
строка
строка
строка

[Куплет 2]
строка
строка
строка
строка

[Припев]
(тот же припев что выше — повторить дословно)

[Бридж]
строка
строка

[Припев]
(тот же припев — повторить дословно)
"""
    return system_prompt, user_prompt


def build_edit_prompt(
    original_song: str,
    edit_request: str,
    genre: str | None = None,
    mood: str | None = None,
    voice: str | None = None,
) -> tuple[str, str]:
    """
    Возвращает (system_prompt, user_prompt) для редактирования песни.
    Принимает опциональный контекст жанра/настроения/голоса чтобы
    модель не съезжала со стиля при правках.
    """
    context_lines = []
    if genre:
        context_lines.append(f"- Жанр: {GENRE_LABELS.get(genre, genre)}")
    if mood:
        context_lines.append(f"- Настроение: {MOOD_LABELS.get(mood, mood)}")
    if voice:
        context_lines.append(f"- Голос: {VOICE_LABELS.get(voice, voice)}")

    context_block = (
        "\nКОНТЕКСТ ОРИГИНАЛА (сохраняй стиль):\n" + "\n".join(context_lines) + "\n"
        if context_lines else ""
    )

    system_prompt = (
        "Ты — редактор песенных текстов. Вносишь ТОЧЕЧНЫЕ правки, "
        "сохраняя структуру, рифму и стиль оригинала. "
        "Если пользователь просит «переписать полностью» или «совсем другую песню» — "
        "сохрани минимум 50% оригинального текста, иначе теряется смысл правок (а не регенерации). "
        "Текст идёт в Suno AI: короткие строки (6-12 слогов), без мета-тегов и эмодзи внутри. "
        "Числа пиши словами. "
        "Откажи одной фразой, если правка содержит оскорбления, угрозы, политику или сексуальный контент."
    )

    user_prompt = f"""ОРИГИНАЛЬНЫЙ ТЕКСТ ПЕСНИ:

{original_song}
{context_block}
ПРАВКА ОТ ПОЛЬЗОВАТЕЛЯ:
{edit_request}

ТРЕБОВАНИЯ:
1. Сохрани структуру: [Куплет 1] / [Припев] / [Куплет 2] / [Припев] / [Бридж] / [Припев].
2. ПРИПЕВ ОДИНАКОВЫЙ во всех повторах. Если меняешь припев — поменяй его во ВСЕХ местах одинаково.
3. Сохрани рифму и длину строк (6-12 слогов).
4. Имя из оригинала должно остаться (минимум одно упоминание в припеве).
5. Никаких мета-тегов [гитара], (пауза), *шёпот*, эмодзи внутри текста.
6. Числа — словами.

ЗАПРЕЩЕНО:
• Предисловия типа «Вот обновлённый текст:» или «Готово!».
• Полностью новый текст — это правки, а не регенерация.
• Объяснения что именно ты поменял.

Верни ТОЛЬКО обновлённый текст песни в том же формате что оригинал.
"""
    return system_prompt, user_prompt
